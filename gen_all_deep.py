# ---- generate each kind via the pmtool interface ----
def gen(kind, title, md):
    payload = {'jsonrpc': '2.0', 'id': 2, 'method': 'tools/call', 'params': {'name': 'pmtool__document_generate', 'arguments': {'title': title, 'markdown': md, 'format': 'docx', 'kind': kind}}}
    inp = ''
    for o in ({'jsonrpc': '2.0', 'id': 1, 'method': 'initialize', 'params': {}}, payload):
        bd = json.dumps(o)
        inp += 'Content-Length: ' + str(len(bd)) + chr(13) + chr(10) + chr(13) + chr(10) + bd
    try:
        p = subprocess.run([EXE, '--mcp'], input=inp.encode('utf-8'), stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, timeout=25)
    except Exception as e:
        print(' %-11s ERROR %s' % (kind, e))
        return None
    for f in re.split(r'Content-Length: \d+\r?\n\r?\n', p.stdout.decode('utf-8', 'replace')):
        f = f.strip()
        if not f:
            continue
        try:
            o = json.loads(f)
        except Exception:
            continue
        if o.get('id') == 2:
            try:
                js = json.loads(o['result']['content'][0]['text'])
                return js
            except Exception:
                return None
    return None

